"""Build the seed SQL from the client's Excel (item NAMES only).

    pip install openpyxl
    python scripts/import_excel.py INVENTORY.xlsx

The Excel is used only as the source of item names. Stock, dates and customers in it are ignored.

Writes
    database/seed_items.sql         the item list: brand, model, size, ply, pattern, category
    database/seed_demo_stock.sql    DEMO ONLY: made-up stock, ROP, lead time and racks so every screen has data
    database/import_report.md       what was cut from the names, and what was guessed or made up

Run order on an empty database: schema.sql, seed_items.sql, seed_users.sql (creates the locations), seed_demo_stock.sql.
Skip seed_demo_stock.sql for real use. Use --no-demo-stock to not even generate it.

Every guess is in import_rules.py so it can be reviewed and changed in one place.
"""
import argparse
import sys
from collections import Counter, OrderedDict

from openpyxl import load_workbook

import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import import_rules as rules   # noqa: E402

STRIDE = 7


def read_names(path):
    """(sheet, name) for every item block in the workbook."""
    out = []
    wb = load_workbook(path, data_only=True)
    for ws in wb:
        for c in range(1, ws.max_column + 1, STRIDE):
            name = rules.clean_name(ws.cell(1, c).value)
            if name:
                out.append((ws.title, name))
    return out


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(int(v))
    return "'" + str(v).replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("xlsx")
    ap.add_argument("--items-out", default="database/seed_items.sql")
    ap.add_argument("--demo-out", default="database/seed_demo_stock.sql")
    ap.add_argument("--report", default="database/import_report.md")
    ap.add_argument("--no-demo-stock", action="store_true")
    a = ap.parse_args()

    items = OrderedDict()
    for sheet, name in read_names(a.xlsx):
        key = name.upper()
        if key not in items:
            items[key] = rules.parse_item(name, sheet)

    counters = Counter()
    for it in items.values():
        counters[it["category"]] += 1
        it["code"] = "%s-%04d" % (rules.CODE_PREFIX[it["category"]], counters[it["category"]])

    out = ["-- Generated by scripts/import_excel.py from %s (item names only). Run AFTER database/schema.sql." %
           os.path.basename(a.xlsx), "BEGIN;", ""]
    for it in items.values():
        out.append("INSERT INTO items (item_code, item_name, brand, model, size, ply_rating, pattern, category) "
                   "VALUES (%s, %s, %s, %s, %s, %s, %s, %s);" %
                   tuple(sql(x) for x in (it["code"], it["name"], it["brand"], it["model"], it["size"], it["ply"],
                                          it["pattern"], it["category"])))
    out += ["", "COMMIT;", ""]
    open(a.items_out, "w", encoding="utf-8").write("\n".join(out))

    n_demo = 0
    if not a.no_demo_stock:
        demo = ["-- DEMO DATA ONLY. Made-up stock, ROP, lead time and racks. Do NOT load this in a real database.",
                "-- Run AFTER schema.sql, seed_items.sql and seed_users.sql (it needs the locations).", "BEGIN;", ""]
        wh = "(SELECT id FROM locations WHERE loc_type = 'warehouse' ORDER BY id LIMIT 1)"
        shop = "(SELECT id FROM locations WHERE loc_type = 'shop' ORDER BY id LIMIT 1)"
        for it in items.values():
            for loc_sql, kind in ((wh, "warehouse"), (shop, "shop")):
                row = rules.demo_row(it, kind)
                if row is None:
                    continue
                n_demo += 1
                item_q = "(SELECT id FROM items WHERE item_code = %s)" % sql(it["code"])
                demo.append("INSERT INTO item_location_settings (item_id, location_id, rop, max_level, lead_time_days, rack) "
                            "VALUES (%s, %s, %d, %d, %d, %s);" % (item_q, loc_sql, row["rop"], row["max_level"],
                                                                 row["lead_time"], sql(row["rack"])))
                if row["qty"] > 0:
                    demo.append("INSERT INTO stock_balances (item_id, location_id, on_hand, reserved) VALUES (%s, %s, %d, 0);"
                                % (item_q, loc_sql, row["qty"]))
                    demo.append("INSERT INTO stock_ledger (item_id, location_id, movement_type, qty_change, balance_after, "
                                "ref_type, remarks, created_at) VALUES (%s, %s, 'opening', %d, %d, 'DEMO', "
                                "'DEMO opening stock', '2026-10-01');" % (item_q, loc_sql, row["qty"], row["qty"]))
        demo += ["", "COMMIT;", ""]
        open(a.demo_out, "w", encoding="utf-8").write("\n".join(demo))

    made = [i for i in items.values() if i["pattern_made_up"]]
    no_rim = [i for i in items.values() if i["category"] == "tire" and i["rim"] is None]
    fixed = [i for i in items.values() if i["parse_note"]]
    r = ["# Excel import report", "", "Source: `%s` (item names only; stock, dates and customers are ignored).\n" % os.path.basename(a.xlsx),
         "| | |", "|---|---|",
         "| Unique items | %d (%s) |" % (len(items), ", ".join("%d %s" % (v, k) for k, v in counters.items())),
         "| Pattern found in the name | %d |" % (sum(1 for i in items.values() if i["pattern"] and not i["pattern_made_up"] and i["pattern"] != "N/A")),
         "| Pattern MADE UP (name had none) | %d |" % len(made),
         "| Demo stock rows (item x location) | %s |" % ("not generated" if a.no_demo_stock else n_demo), "",
         "## How it was decided", "",
         "- Items are classified by their specs only: category, brand, model, size, ply and pattern. There is no vehicle type.",
         "- Pattern is the tread type. If the name has a tread word (RIB, LUG, MIX, SOLID, LOADER...) it is used. Otherwise one is made up from the size (small metric sizes get All-Season / Touring, truck sizes get Rib / Lug / Mixed, very large sizes get Farm / Loader / Rock). Tubes, flaps and rims get `N/A`.",
         "- Model is what is left of the name after size, ply and tread word (for example `BY616`).",
         "- Ply is only what the name says. Nothing is made up for it.",
         "- Item codes are generated (TIR-0001, TUB-0001, FLP-0001, OTH-0001). The client has no codes of their own.",
         "- Demo racks are grouped by rim size: A up to 16 in, B 17 to 19.5, C 20 to 22.5, D 23 and up, E tubes and flaps, F rims.",
         "- Item names are kept exactly as the client wrote them. Obvious brand typos are fixed in the brand column only.",
         "- Unit price is not stored: this system has no prices.", ""]
    r += ["## Names that needed a manual fix before reading (%d)" % len(fixed), ""]
    r += ["- `%s`: %s" % (i["name"], i["parse_note"]) for i in fixed] or ["None."]
    r += ["", "## Tires whose size could not be read (%d). Please check" % len(no_rim), ""]
    r += ["- `%s`" % i["name"] for i in no_rim] or ["None."]
    open(a.report, "w", encoding="utf-8").write("\n".join(r) + "\n")
    print("items %d, pattern made up %d, size unread %d, demo rows %d" % (len(items), len(made), len(no_rim), n_demo))


if __name__ == "__main__":
    main()
